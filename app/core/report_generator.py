from datetime import datetime
from typing import Dict, Any

def generate_incident_report(analysis_result: Dict[str, Any], candidate_alias: str = "Student/Candidate") -> Dict[str, str]:
    """
    Generates ready-to-file incident documentation and grievance letters
    for India's National Cyber Crime Portal (cybercrime.gov.in / Helpline 1930)
    and university placement cells.
    """
    now_str = datetime.now().strftime("%d-%B-%Y %I:%M %p")
    company = analysis_result.get("claimed_company", "Impersonated Organization")
    domain = analysis_result.get("domain_analysis", {}).get("domain", "Unknown Domain")
    score = analysis_result.get("risk_score", 0)
    signals = analysis_result.get("signals", [])
    
    signals_summary = "\n".join([f"- [{s.get('category')}] {s.get('title')}: {s.get('explanation')}" for s in signals])
    
    # 1. Cyber Crime Portal 1930 Complaint Text
    cybercrime_draft = f"""NATIONAL CYBER CRIME REPORTING PORTAL (cybercrime.gov.in)
INCIDENT COMPLAINT DRAFT (SECTION 66C & 66D INFORMATION TECHNOLOGY ACT 2000)
--------------------------------------------------------------------------------
Date of Filing Preparation: {now_str}
Incident Category: Online Job Fraud / Identity Theft by Impersonation
Sub-Category: Forged Appointment Letter & PII / Advance-Fee Solicitation

1. SUSPECT DETAILS:
- Impersonated Company/Brand: {company}
- Fraudulent Domain / Sender Email: {domain}
- Off-Platform Channels (if any): Telegram / WhatsApp handles referenced in communication
- Severity / Threat Level Assessed by OfferShield AI: {score}/100 (CRITICAL MALICIOUS)

2. MODUS OPERANDI (INCIDENT SUMMARY):
The perpetrator impersonated recruitment officials from {company} and distributed fraudulent employment/internship appointment materials. Under the pretext of pre-joining document verification and refundable equipment/asset dispatch fees, the attacker attempted to harvest sensitive identity records (Aadhaar/PAN/banking credentials) and requested unauthorized financial transactions.

3. FORENSIC EVIDENCE & RED FLAGS DETECTED:
{signals_summary}

4. RELIEF SOUGHT:
- Immediate blacklisting and blocking of the phishing domain '{domain}' on Indian ISPs and Sanchar Saathi (Chakshu portal).
- Freezing of recipient UPI accounts/wallets linked to this campaign.
- Registration of official cyber fraud complaint against the syndicate.
--------------------------------------------------------------------------------
Generated automatically by OfferShield AI (Zero-Data-Retention Incident Response Engine)
"""

    # 2. Campus Placement Cell Warning Notice
    placement_cell_notice = f"""URGENT SECURITY ALERT: Fraudulent Campus Recruitment Drive Detected
TO: Head of Training & Placement, Student Affairs
DATE: {now_str}
SUBJECT: Impersonation Alert - Fake Offer Letters Mimicking {company}

Dear Placement Officer,

This is an automated safety alert generated by OfferShield AI.
A student was targeted with a counterfeit job offer impersonating '{company}'.

Key Threat Indicators:
- Sender Email / Domain: {domain}
- Attack Mechanism: Threat of offer cancellation unless candidate transfers upfront fees or uploads un-redacted Aadhaar/PAN cards.
- Risk Score: {score}/100

Recommended Campus Actions:
1. Issue a circular alerting final-year students that {company} does NOT charge equipment deposits or conduct recruitment via personal messengers.
2. Instruct candidates to verify any suspicious offer letter directly with the official campus placement cell before sharing Aadhaar or bank account details.
"""

    return {
        "cybercrime_portal_complaint": cybercrime_draft.strip(),
        "placement_cell_notice": placement_cell_notice.strip(),
        "helpline_number": "1930",
        "portal_url": "https://cybercrime.gov.in",
        "sanchar_saathi_url": "https://sancharsaathi.gov.in/sfc"
    }
